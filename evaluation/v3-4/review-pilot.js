import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {readAttemptLedger} from '../checkpoints.js';

const root=dirname(fileURLToPath(import.meta.url));
const at=name=>join(root,name);
const read=async name=>JSON.parse(await readFile(at(name),'utf8'));
const sha=value=>createHash('sha256').update(JSON.stringify(value)).digest('hex');
const [freeze,packet,semantic,approval]=await Promise.all(['pilot-freeze.json','pilot-review-packet.json','pilot-semantic-review.json','pilot-label-approval.json'].map(read));
assert.equal(packet.schemaVersion,1);
assert.equal(packet.contractVersion,'3.4.0');
assert.equal(packet.freezeChecksum,sha(freeze));
assert.equal(packet.approvalChecksum,sha(approval));
assert.equal(packet.items.length,16);
assert.equal(packet.attempts,16);
const attempts=await readAttemptLedger(at('pilot-attempts.json'),{identity:freeze});
assert.equal(attempts.length,16);
assert.ok(attempts.every(kind=>kind==='feedback'));
assert.equal(semantic.schemaVersion,1);
assert.equal(semantic.contractVersion,'3.4.0');
assert.equal(semantic.reviewPacketChecksum,sha(packet));
assert.ok(semantic.reviewer?.trim()&&Number.isFinite(Date.parse(semantic.reviewedAt)));
assert.equal(semantic.reviewedOutputs,16);
assert.equal(semantic.reviewedPairs,96);
assert.equal(semantic.reviews.length,16);
for(const [index,review] of semantic.reviews.entries()){
  const item=packet.items[index];
  assert.equal(review.caseId,item.caseId);
  assert.equal(review.repeat,item.repeat);
  assert.equal(review.outputChecksum,item.outputChecksum);
  assert.equal(review.ratingMissesVerified,true);
  assert.ok(['consistent','inconsistent'].includes(review.verdict));
  assert.ok(Array.isArray(review.contradictoryPairs));
  assert.equal(review.verdict==='consistent',review.contradictoryPairs.length===0);
}
const inconsistent=semantic.reviews.filter(review=>review.verdict==='inconsistent');
const dimensions=['relevance','support','structure','englishExpression'];
const ratingGate=packet.outputLevelPass>=12&&dimensions.every(name=>packet.dimensionMisses[name]<=4);
const automaticGate=packet.automaticPass===true&&packet.items.length===16&&attempts.length===16;
const semanticGate=inconsistent.length===0;
const reviewed={schemaVersion:1,contractVersion:'3.4.0',generatedAt:new Date().toISOString(),usage:{subscriptionFeedbackRequests:attempts.length,subscriptionRequestCap:16,independentAiReviewerInvocations:4,reviewerInvocationCap:4},artifactChecksums:{freeze:sha(freeze),reviewPacket:sha(packet),semanticReview:sha(semantic),approvedLabels:sha(approval)},automaticGate:{pass:automaticGate,outputs:packet.items.length},ratingGate:{pass:ratingGate,outputLevelPass:packet.outputLevelPass,total:16,dimensionMisses:packet.dimensionMisses},bilingualGate:{pass:semanticGate,consistentOutputs:16-inconsistent.length,total:16,reviewedPairs:semantic.reviewedPairs,inconsistent:inconsistent.map(({caseId,repeat,outputChecksum,contradictoryPairs})=>({caseId,repeat,outputChecksum,contradictoryPairs}))},pilotStatus:automaticGate&&ratingGate&&semanticGate?'GO_FOR_SEPARATE_FULL_EVALUATION_APPROVAL':'NO_GO',releaseStatus:'BLOCKED',note:'Diagnostic pilot only. Historical 3.3 output, labels and release verdict are unchanged; this report cannot validate v1.0.0.'};
await writeFile(at('pilot-reviewed.json'),JSON.stringify(reviewed,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({output:'evaluation/v3-4/pilot-reviewed.json',pilotStatus:reviewed.pilotStatus,automaticGate:automaticGate,ratingGate:ratingGate,bilingualGate:semanticGate,requests:attempts.length},null,2));
