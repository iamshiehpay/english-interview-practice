import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {readAttemptLedger} from '../checkpoints.js';

const root=dirname(fileURLToPath(import.meta.url));
const at=name=>join(root,name);
const read=async name=>JSON.parse(await readFile(at(name),'utf8'));
const readLuna=async name=>JSON.parse(await readFile(join(root,'..','v3-4',name),'utf8'));
const sha=value=>createHash('sha256').update(JSON.stringify(value)).digest('hex');
const [freeze,packet,semantic,approval,lunaPacket,lunaSemantic,verification]=await Promise.all([read('pilot-freeze.json'),read('pilot-review-packet.json'),read('pilot-semantic-review.json'),readLuna('pilot-label-approval.json'),readLuna('pilot-review-packet.json'),readLuna('pilot-semantic-review.json'),read('verification-attempt.json')]);
assert.equal(verification.schemaVersion,1);
assert.equal(verification.status,'completed');
assert.equal(verification.model,'gpt-5.6-sol');
assert.equal(verification.requestCap,1);
assert.equal(packet.schemaVersion,1);
assert.equal(packet.contractVersion,'3.4.0');
assert.equal(freeze.model,'gpt-5.6-sol');
assert.equal(packet.freezeChecksum,sha(freeze));
assert.equal(packet.approvalChecksum,sha(approval));
assert.equal(packet.items.length,16);
assert.equal(packet.attempts,16);
const attempts=await readAttemptLedger(at('pilot-attempts.json'),{identity:freeze});
assert.equal(attempts.length,16);
assert.ok(attempts.every(kind=>kind==='feedback'));
assert.equal(semantic.schemaVersion,1);
assert.equal(semantic.contractVersion,'3.4.0');
assert.equal(semantic.reviewPacketChecksum,sha(packet));
assert.ok(semantic.reviewer?.trim()&&Number.isFinite(Date.parse(semantic.reviewedAt)));
assert.equal(semantic.reviewedOutputs,16);
assert.equal(semantic.reviewedPairs,96);
assert.equal(semantic.reviews.length,16);
for(const [index,review] of semantic.reviews.entries()){
  const item=packet.items[index];
  assert.equal(review.caseId,item.caseId);
  assert.equal(review.repeat,item.repeat);
  assert.equal(review.outputChecksum,item.outputChecksum);
  assert.equal(review.ratingMissesVerified,true);
  assert.ok(['consistent','inconsistent'].includes(review.verdict));
  assert.ok(Array.isArray(review.contradictoryPairs));
  assert.equal(review.verdict==='consistent',review.contradictoryPairs.length===0);
}
const inconsistent=semantic.reviews.filter(review=>review.verdict==='inconsistent');
const dimensions=['relevance','support','structure','englishExpression'];
const ratingGate=packet.outputLevelPass>=14&&dimensions.every(name=>packet.dimensionMisses[name]<=2);
const automaticGate=packet.automaticPass===true&&packet.items.length===16&&attempts.length===16;
const semanticGate=inconsistent.length===0;
assert.equal(lunaPacket.items.length,16);
assert.equal(lunaSemantic.reviewPacketChecksum,sha(lunaPacket));
assert.equal(lunaSemantic.reviews.length,16);
const pairedComparison=packet.items.map((item,index)=>{
  const prior=lunaPacket.items[index],priorReview=lunaSemantic.reviews[index],solReview=semantic.reviews[index];
  assert.equal(prior.caseId,item.caseId);assert.equal(prior.repeat,item.repeat);assert.equal(prior.inputChecksum,item.inputChecksum);
  assert.equal(priorReview.outputChecksum,prior.outputChecksum);
  return {caseId:item.caseId,repeat:item.repeat,luna:{ratingPass:prior.ratingMisses.length===0,semanticVerdict:priorReview.verdict},sol:{ratingPass:item.ratingMisses.length===0,semanticVerdict:solReview.verdict}};
});
const reviewed={schemaVersion:1,contractVersion:'3.4.0',generatedAt:new Date().toISOString(),usage:{subscriptionVerificationRequests:1,subscriptionFeedbackRequests:attempts.length,subscriptionRequestCap:17,independentAiReviewerInvocations:2,reviewerInvocationCap:2},artifactChecksums:{verification:sha(verification),freeze:sha(freeze),reviewPacket:sha(packet),semanticReview:sha(semantic),approvedLabels:sha(approval),lunaReviewPacket:sha(lunaPacket),lunaSemanticReview:sha(lunaSemantic)},automaticGate:{pass:automaticGate,outputs:packet.items.length},ratingGate:{pass:ratingGate,outputLevelPass:packet.outputLevelPass,total:16,dimensionMisses:packet.dimensionMisses},bilingualGate:{pass:semanticGate,consistentOutputs:16-inconsistent.length,total:16,reviewedPairs:semantic.reviewedPairs,inconsistent:inconsistent.map(({caseId,repeat,outputChecksum,contradictoryPairs})=>({caseId,repeat,outputChecksum,contradictoryPairs}))},pairedComparison,pilotStatus:automaticGate&&ratingGate&&semanticGate?'GO_FOR_SEPARATE_FULL_EVALUATION_APPROVAL':'NO_GO',releaseStatus:'BLOCKED',note:'Controlled model comparison only. Historical 3.3 output, labels and release verdict are unchanged; this report cannot validate v1.0.0.'};
await writeFile(at('pilot-reviewed.json'),JSON.stringify(reviewed,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({output:'evaluation/v3-4-sol/pilot-reviewed.json',pilotStatus:reviewed.pilotStatus,automaticGate:automaticGate,ratingGate:ratingGate,bilingualGate:semanticGate,subscriptionRequests:attempts.length+1},null,2));
